#!/usr/bin/env node
/**
 * Extract the brand mark from the reference screenshot into an alpha-masked
 * PNG data URI.
 *
 * The reference mark is a hand-drawn three-loop knot, not a parametric figure:
 * three rows through it are not consistent with any single-ellipse construction,
 * so tracing it back into SVG paths means redrawing it by eye. The mark is a
 * brand asset rather than type, so the skin ships the reference's own pixels,
 * cropped at capture resolution (DPR 2) and masked to alpha so the tile's fill
 * shows through and the mark composites on any background.
 *
 * Writes `src/client/hero/mark-data.ts`. Re-run after changing the reference:
 *
 *   node scripts/make-mark.mjs
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { createRequire } from 'node:module'
import { decode, helpers } from './png.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const require = createRequire(join(here, '..', '..', 'deepseek-harness', 'apps', 'web', 'package.json'))
const sharp = require('sharp')

/** Mark ink box in CSS px, measured off the reference (see scripts/probe.mjs). */
const BOX = { x: 732.5, y: 232.5, w: 78, h: 72.5 }
/** Flat ink colour of the mark; every other pixel is an antialiased edge. */
const INK = [0x51, 0x51, 0x51]

const scale = 2
const left = Math.round(BOX.x * scale)
const top = Math.round(BOX.y * scale)
const width = Math.round(BOX.w * scale)
const height = Math.round(BOX.h * scale)

const img = decode(join(here, '..', 'reference', 'screenshot.png'))
const { at } = helpers(img, scale)

const rgba = Buffer.alloc(width * height * 4)
for (let y = 0; y < height; y++) {
  for (let x = 0; x < width; x++) {
    const [r] = at(left + x, top + y)
    // Alpha from coverage: 0 at paper white, 255 at the flat ink value.
    const alpha = Math.max(0, Math.min(255, Math.round(((255 - r) / (255 - INK[0])) * 255)))
    const o = (y * width + x) * 4
    rgba[o] = INK[0]
    rgba[o + 1] = INK[1]
    rgba[o + 2] = INK[2]
    rgba[o + 3] = alpha
  }
}

const png = await sharp(rgba, { raw: { width, height, channels: 4 } })
  .png({ compressionLevel: 9, palette: false })
  .toBuffer()

const out = join(here, '..', 'src', 'client', 'hero', 'mark-data.ts')
writeFileSync(
  out,
  `/**
 * Generated by scripts/make-mark.mjs — do not edit.
 *
 * The reference brand mark at capture resolution (${width}x${height}, DPR 2),
 * alpha-masked so it composites on the tile's own fill. Rendered at
 * ${BOX.w}x${BOX.h} CSS px.
 */
export const MARK_DATA_URI =
  'data:image/png;base64,${png.toString('base64')}'
`,
)
console.log(`wrote ${out} — ${width}x${height} px, ${png.length} bytes`)
